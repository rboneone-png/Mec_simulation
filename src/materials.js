/** 工程應力-應變曲線（彈性 → 加工硬化 → 頸縮） */
export function stressStrainCurve(m, n = 200) {
  const ey = m.sy / m.E;
  const eu = Math.max(m.eu, ey * 1.5);
  const ef = Math.max(m.ef, eu * 1.05);
  const sf = m.su * 0.85;
  const pts = [[0, 0], [ey, m.sy]];
  for (let i = 1; i <= n; i++) {
    const e = ey + ((ef - ey) * i) / n;
    let s;
    if (e <= eu) {
      const x = (e - ey) / (eu - ey);
      s = m.sy + (m.su - m.sy) * (1 - (1 - x) ** 2);
    } else {
      const x = (e - eu) / (ef - eu);
      s = m.su - (m.su - sf) * x * x;
    }
    pts.push([e, s]);
  }
  return { pts, ey, eu, ef };
}
